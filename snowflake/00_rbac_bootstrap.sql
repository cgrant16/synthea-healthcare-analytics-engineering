-- ============================================================
-- 1. Warehouses
-- ============================================================
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS SYNTHEA_INGEST_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'For loading Synthea CSVs from S3 into RAW';

CREATE WAREHOUSE IF NOT EXISTS SYNTHEA_TRANSFORM_WH
  WITH WAREHOUSE_SIZE = 'SMALL'          -- bump to MEDIUM if builds are slow
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'For dbt Core builds';

CREATE WAREHOUSE IF NOT EXISTS SYNTHEA_ANALYST_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'For analyst queries against marts';

-- ============================================================
-- 2. Roles
-- ============================================================
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS SYNTHEA_INGEST_ROLE;
CREATE ROLE IF NOT EXISTS SYNTHEA_DBT_ROLE;
CREATE ROLE IF NOT EXISTS SYNTHEA_ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS SYNTHEA_DEVELOPER_ROLE;

-- Role hierarchy
GRANT ROLE SYNTHEA_INGEST_ROLE TO ROLE SYNTHEA_DEVELOPER_ROLE;
GRANT ROLE SYNTHEA_DBT_ROLE    TO ROLE SYNTHEA_DEVELOPER_ROLE;

-- Roll up to SYSADMIN so admins can see everything
GRANT ROLE SYNTHEA_DEVELOPER_ROLE TO ROLE SYSADMIN;
GRANT ROLE SYNTHEA_ANALYST_ROLE   TO ROLE SYSADMIN;

-- ============================================================
-- 3. Database & Schema Ownership / Privileges
-- ============================================================
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS SYNTHEA;

CREATE SCHEMA IF NOT EXISTS SYNTHEA.RAW;
CREATE SCHEMA IF NOT EXISTS SYNTHEA.STAGING;
CREATE SCHEMA IF NOT EXISTS SYNTHEA.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS SYNTHEA.MARTS;

-- Optional: managed access schemas (stronger control)
-- ALTER SCHEMA SYNTHEA.RAW SET MANAGED ACCESS;
-- ALTER SCHEMA SYNTHEA.STAGING SET MANAGED ACCESS;
-- ALTER SCHEMA SYNTHEA.INTERMEDIATE SET MANAGED ACCESS;
-- ALTER SCHEMA SYNTHEA.MARTS SET MANAGED ACCESS;

-- ============================================================
-- 4. Privileges for SYNTHEA_INGEST_ROLE (data loading)
-- ============================================================
USE ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE SYNTHEA_INGEST_WH TO ROLE SYNTHEA_INGEST_ROLE;
GRANT USAGE ON DATABASE SYNTHEA TO ROLE SYNTHEA_INGEST_ROLE;
GRANT USAGE ON SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;

GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;

GRANT USAGE ON ALL STAGES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;
GRANT USAGE ON FUTURE STAGES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_INGEST_ROLE;

-- ============================================================
-- 5. Privileges for SYNTHEA_DBT_ROLE (transformations)
-- ============================================================
GRANT USAGE ON WAREHOUSE SYNTHEA_TRANSFORM_WH TO ROLE SYNTHEA_DBT_ROLE;
GRANT USAGE ON DATABASE SYNTHEA TO ROLE SYNTHEA_DBT_ROLE;

-- Read RAW
GRANT USAGE ON SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SYNTHEA.RAW TO ROLE SYNTHEA_DBT_ROLE;

-- Full control of transformation schemas
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE PROCEDURE
  ON SCHEMA SYNTHEA.STAGING TO ROLE SYNTHEA_DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE PROCEDURE
  ON SCHEMA SYNTHEA.INTERMEDIATE TO ROLE SYNTHEA_DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE PROCEDURE
  ON SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_DBT_ROLE;

GRANT ALL ON ALL TABLES IN SCHEMA SYNTHEA.STAGING TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON ALL VIEWS IN SCHEMA SYNTHEA.STAGING TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA SYNTHEA.STAGING TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN SCHEMA SYNTHEA.STAGING TO ROLE SYNTHEA_DBT_ROLE;

GRANT ALL ON ALL TABLES IN SCHEMA SYNTHEA.INTERMEDIATE TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON ALL VIEWS IN SCHEMA SYNTHEA.INTERMEDIATE TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA SYNTHEA.INTERMEDIATE TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN SCHEMA SYNTHEA.INTERMEDIATE TO ROLE SYNTHEA_DBT_ROLE;

GRANT ALL ON ALL TABLES IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON ALL VIEWS IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_DBT_ROLE;

-- ============================================================
-- 6. Privileges for SYNTHEA_ANALYST_ROLE (consumption)
-- ============================================================
GRANT USAGE ON WAREHOUSE SYNTHEA_ANALYST_WH TO ROLE SYNTHEA_ANALYST_ROLE;
GRANT USAGE ON DATABASE SYNTHEA TO ROLE SYNTHEA_ANALYST_ROLE;

GRANT USAGE ON SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_ANALYST_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SYNTHEA.MARTS TO ROLE SYNTHEA_ANALYST_ROLE;

-- ============================================================
-- 7. Developer role gets warehouse access too
-- ============================================================
GRANT USAGE ON WAREHOUSE SYNTHEA_TRANSFORM_WH TO ROLE SYNTHEA_DEVELOPER_ROLE;
GRANT USAGE ON WAREHOUSE SYNTHEA_INGEST_WH TO ROLE SYNTHEA_DEVELOPER_ROLE;

-- ============================================================
-- 8. Service users (key-pair auth to be attached later:
--    ALTER USER ... SET RSA_PUBLIC_KEY = '...')
-- ============================================================
USE ROLE SECURITYADMIN;

CREATE USER IF NOT EXISTS SYNTHEA_DBT_USER
  TYPE = SERVICE
  DEFAULT_ROLE = SYNTHEA_DBT_ROLE
  DEFAULT_WAREHOUSE = SYNTHEA_TRANSFORM_WH
  COMMENT = 'Service user for dbt Core builds';

GRANT ROLE SYNTHEA_DBT_ROLE TO USER SYNTHEA_DBT_USER;

CREATE USER IF NOT EXISTS SYNTHEA_INGEST_USER
  TYPE = SERVICE
  DEFAULT_ROLE = SYNTHEA_INGEST_ROLE
  DEFAULT_WAREHOUSE = SYNTHEA_INGEST_WH
  COMMENT = 'Service user for S3 loads';

GRANT ROLE SYNTHEA_INGEST_ROLE TO USER SYNTHEA_INGEST_USER;
