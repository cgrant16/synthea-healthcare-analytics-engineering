/* =============================================================================
   05_raw_2026_landing.sql   (four sections, each run as a different role)
   Author: Cortwright Grant

   Lands the current-version Synthea dataset (10,000 Massachusetts patients,
   18 CSV tables, generated by aws/mac_generate_and_upload_2026.sh) in
   SYNTHEA.RAW_2026, next to the 2017 extract in SYNTHEA.RAW.

   Why a second schema: both datasets have tables called PATIENTS, ENCOUNTERS,
   and so on, with different columns. They are different populations and are
   never joined, so each keeps its own landing schema.

   Order:
     1. aws/mac_generate_and_upload_2026.sh  (UPLOAD=1)   files in S3
     2. aws/mac_add_prefix_to_iam_policy.sh  (APPLY=1)    AWS allows the prefix
     3. this file, sections A -> D                         Snowflake allows it, then loads

   Find/replace before running:  <BUCKET>
   ============================================================================= */

-- =============================================================================
-- A. Schema                                                        (SYSADMIN)
-- =============================================================================
USE ROLE SYSADMIN;

CREATE SCHEMA IF NOT EXISTS SYNTHEA.RAW_2026
    COMMENT = 'Landing zone: current-version Synthea (2026 build), 10,000 MA patients, 18 CSV tables';

-- =============================================================================
-- B. Grants                                                   (SECURITYADMIN)
--    Same shape as RAW in 00_rbac_bootstrap.sql, plus CREATE PROCEDURE (the
--    gap that 01_storage_integration.sql closed for RAW).
-- =============================================================================
USE ROLE SECURITYADMIN;

-- Ingest role: owns the stage, the load procedure and the tables.
GRANT USAGE ON SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_INGEST_ROLE;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE PROCEDURE
    ON SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_INGEST_ROLE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_INGEST_ROLE;
GRANT USAGE ON FUTURE STAGES IN SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_INGEST_ROLE;

-- dbt role: read-only, exactly as on RAW.
GRANT USAGE  ON SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SYNTHEA.RAW_2026 TO ROLE SYNTHEA_DBT_ROLE;

-- =============================================================================
-- C. Storage integration: allow the new prefix                 (ACCOUNTADMIN)
--    ALTER, never CREATE OR REPLACE: replacing the integration mints a new
--    external ID and breaks the IAM trust policy. ALTER keeps it.
--    The list REPLACES the old one, so the 2017 prefix must stay in it.
-- =============================================================================
USE ROLE ACCOUNTADMIN;

ALTER STORAGE INTEGRATION SYNTHEA_S3_INT SET
    STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET>/synthea-v2/csv/',
                                 's3://<BUCKET>/synthea-2026/csv/');

-- Check: both locations listed, and STORAGE_AWS_EXTERNAL_ID unchanged.
DESC INTEGRATION SYNTHEA_S3_INT;

-- =============================================================================
-- D. Stage, load procedure and loads                    (SYNTHEA_INGEST_ROLE)
-- =============================================================================
USE ROLE      SYNTHEA_INGEST_ROLE;
USE WAREHOUSE SYNTHEA_INGEST_WH;
USE SCHEMA    SYNTHEA.RAW_2026;

-- D1. Stage. The two CSV file formats in SYNTHEA.RAW are reused as they are;
--     the files have the same dialect (comma, optional double quotes, UTF-8).
CREATE STAGE IF NOT EXISTS SYNTHEA.RAW_2026.SYNTHEA_2026_S3_STAGE
    STORAGE_INTEGRATION = SYNTHEA_S3_INT
    URL                 = 's3://<BUCKET>/synthea-2026/csv/'
    FILE_FORMAT         = SYNTHEA.RAW.SYNTHEA_CSV_HEADER_FORMAT
    COMMENT             = 'Current-version Synthea (2026 build) CSV landing zone; one sub-folder per table';

-- D2. Can Snowflake see the files?  (Access Denied -> the IAM policy or section C
--     has not taken effect yet; IAM changes need about a minute.)
LIST @SYNTHEA.RAW_2026.SYNTHEA_2026_S3_STAGE;

SELECT SPLIT_PART("name", '/', -2)            AS table_folder,
       COUNT(*)                               AS files,
       ROUND(SUM("size") / POWER(1024, 3), 2) AS size_gb
FROM   TABLE(RESULT_SCAN(LAST_QUERY_ID()))
GROUP  BY 1
ORDER  BY 1;

-- D3. Load procedure: the same three steps as SYNTHEA.RAW.LOAD_RAW_TABLE
--     (table from the CSV header, all VARCHAR; audit columns; COPY by name),
--     pointed at this schema and stage. See 03_raw_tables_and_load.sql for the
--     reasoning behind each choice.
CREATE OR REPLACE PROCEDURE SYNTHEA.RAW_2026.LOAD_RAW_TABLE(SOURCE_NAME VARCHAR)
RETURNS TABLE()
LANGUAGE SQL
COMMENT = 'Create RAW_2026.<SOURCE_NAME> from its CSV header (all VARCHAR) and COPY new files from the stage folder'
EXECUTE AS OWNER
AS
$$
DECLARE
    tbl        VARCHAR;
    stage_path VARCHAR;
    stmt       VARCHAR;
    copy_result RESULTSET;
    bad_name   EXCEPTION (-20001, 'SOURCE_NAME must be lowercase letters/underscores, e.g. ''patients''');
BEGIN
    -- Guard against SQL injection: the name is concatenated into DDL below.
    IF (NOT REGEXP_LIKE(source_name, '^[a-z_]+$')) THEN
        RAISE bad_name;
    END IF;

    tbl        := 'SYNTHEA.RAW_2026.' || UPPER(source_name);
    stage_path := '@SYNTHEA.RAW_2026.SYNTHEA_2026_S3_STAGE/' || source_name || '/';

    -- 1. Table from header (fails here if the S3 folder is empty / misnamed)
    stmt := 'CREATE TABLE IF NOT EXISTS ' || tbl || ' USING TEMPLATE (
                SELECT ARRAY_AGG(OBJECT_CONSTRUCT(
                           ''COLUMN_NAME'', UPPER(column_name),
                           ''TYPE'',        ''VARCHAR'',
                           ''NULLABLE'',    TRUE))
                       WITHIN GROUP (ORDER BY order_id)
                FROM TABLE(INFER_SCHEMA(
                         LOCATION             => ''' || stage_path || ''',
                         FILE_FORMAT          => ''SYNTHEA.RAW.SYNTHEA_CSV_HEADER_FORMAT'',
                         MAX_FILE_COUNT       => 1,
                         MAX_RECORDS_PER_FILE => 100)))';
    EXECUTE IMMEDIATE :stmt;

    -- 2. Audit columns
    stmt := 'ALTER TABLE ' || tbl || ' ADD COLUMN IF NOT EXISTS _SOURCE_FILE VARCHAR';
    EXECUTE IMMEDIATE :stmt;
    stmt := 'ALTER TABLE ' || tbl || ' ADD COLUMN IF NOT EXISTS _SOURCE_ROW NUMBER';
    EXECUTE IMMEDIATE :stmt;
    stmt := 'ALTER TABLE ' || tbl || ' ADD COLUMN IF NOT EXISTS _LOADED_AT TIMESTAMP_LTZ';
    EXECUTE IMMEDIATE :stmt;

    -- 3. Load
    stmt := 'COPY INTO ' || tbl || '
             FROM ' || stage_path || '
             FILE_FORMAT          = (FORMAT_NAME = ''SYNTHEA.RAW.SYNTHEA_CSV_HEADER_FORMAT'')
             MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
             INCLUDE_METADATA     = (
                 _SOURCE_FILE = METADATA$FILENAME,
                 _SOURCE_ROW  = METADATA$FILE_ROW_NUMBER,
                 _LOADED_AT   = METADATA$START_SCAN_TIME)
             ON_ERROR             = ABORT_STATEMENT';
    copy_result := (EXECUTE IMMEDIATE :stmt);

    -- One row per file: status, rows_parsed, rows_loaded, first_error...
    RETURN TABLE(copy_result);
END;
$$;

-- D4. Loads. Reference tables first (tiny, so a format surprise shows up fast),
--     then clinical tables, then the two large claims tables.
--     Safe to re-run: already-loaded files are skipped. Never add FORCE = TRUE.
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('payers');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('organizations');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('providers');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('patients');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('payer_transitions');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('allergies');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('careplans');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('devices');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('supplies');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('immunizations');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('conditions');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('medications');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('encounters');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('procedures');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('imaging_studies');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('observations');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('claims');
CALL SYNTHEA.RAW_2026.LOAD_RAW_TABLE('claims_transactions');   -- by far the largest

